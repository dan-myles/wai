// Builds the release: one standalone `wai` binary per platform (the bridge, CLI and addon in one
// file) plus SHA256SUMS, into dist/. Usage: bun scripts/build.ts [target ...]
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { assetName } from "../src/update";

const ROOT = resolve(import.meta.dir, "..");
const ADDON = resolve(ROOT, "../addon");
const DIST = join(ROOT, "dist");
const TARGETS: Record<string, [NodeJS.Platform, NodeJS.Architecture]> = {
  "bun-darwin-arm64": ["darwin", "arm64"],
  "bun-darwin-x64": ["darwin", "x64"],
  "bun-windows-x64": ["win32", "x64"],
  "bun-linux-x64": ["linux", "x64"],
};
// Player data and dev files that never ship.
const SKIP = /^(Data\.lua|Generated\.lua|ModuleDefs\.lua|\.manifest\.json|ui\/|test\/)|\.tmp$|\.DS_Store$/;

async function addonFiles(dir = ADDON): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    const rel = relative(ADDON, path).split("\\").join("/");
    if (SKIP.test(entry.isDirectory() ? `${rel}/` : rel)) continue;
    if (entry.isDirectory()) out.push(...(await addonFiles(path)));
    else out.push(rel);
  }
  return out.sort();
}

// src/embedded-addon.ts: every shipped addon file, embedded into the binary.
const files = await addonFiles();
const lines = files.map((f, i) => `import f${i} from ${JSON.stringify(`../../addon/${f}`)} with { type: "file" };`);
await writeFile(
  join(ROOT, "src", "embedded-addon.ts"),
  `// Generated by scripts/build.ts. Do not edit.\n${lines.join("\n")}\n\nexport const files: [string, string][] = [\n${files
    .map((f, i) => `  [${JSON.stringify(f)}, f${i} as unknown as string],`)
    .join("\n")}\n];\n`,
);

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });
const targets = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(TARGETS);
const sums: string[] = [];
for (const target of targets) {
  const [platform, arch] = TARGETS[target] ?? [];
  if (!platform) throw new Error(`unknown target ${target}`);
  const name = assetName(platform, arch);
  const proc = Bun.spawnSync(["bun", "build", "src/cli.ts", "--compile", "--minify", `--target=${target}`, `--outfile=${join(DIST, name)}`], {
    cwd: ROOT, stdout: "inherit", stderr: "inherit",
  });
  if (proc.exitCode !== 0) process.exit(proc.exitCode ?? 1);
  const bytes = new Uint8Array(await Bun.file(join(DIST, name)).arrayBuffer());
  sums.push(`${new Bun.CryptoHasher("sha256").update(bytes).digest("hex")}  ${name}`);
}
await writeFile(join(DIST, "SHA256SUMS"), `${sums.join("\n")}\n`);
console.log(`built ${targets.length} binaries with ${files.length} addon files into dist/`);
